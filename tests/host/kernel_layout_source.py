def _relative_path(path: Path) -> str:
    candidate = path if path.is_absolute() else REPOSITORY_ROOT / path
    return candidate.relative_to(REPOSITORY_ROOT).as_posix()


def _current_relative_path(logical: str) -> str:
    if logical not in KERNEL_FILE_FACTS:
        raise AssertionError(f"unknown kernel source: {logical}")
    if logical in KERNEL_PHYSICAL_OWNER_MIGRATION:
        return logical
    return KERNEL_LOGICAL_TO_PHYSICAL[logical]


def current_path(root: Path, logical: str) -> Path:
    return root / _current_relative_path(logical)


def _member_errors(root: Path, logical: str) -> tuple[str, ...]:
    physical, expected_mode, _, _ = KERNEL_FILE_FACTS[logical]
    pending = logical in KERNEL_PHYSICAL_OWNER_MIGRATION
    selected = root / (logical if pending else physical)
    alternate = root / (physical if pending else logical)
    errors = []
    try:
        selected_status = selected.lstat()
    except FileNotFoundError:
        errors.append(f"missing current owner: {selected.relative_to(root)}")
        selected_status = None
    if selected_status is not None:
        if stat.S_ISLNK(selected_status.st_mode):
            errors.append(f"linked current owner: {selected.relative_to(root)}")
        elif not stat.S_ISREG(selected_status.st_mode):
            errors.append(f"non-ordinary current owner: {selected.relative_to(root)}")
        if f"{stat.S_IMODE(selected_status.st_mode):03o}" != expected_mode[-3:]:
            errors.append(f"mode mismatch: {selected.relative_to(root)}")
        if selected_status.st_nlink != 1:
            errors.append(f"hard-linked current owner: {selected.relative_to(root)}")
    try:
        alternate.lstat()
    except FileNotFoundError:
        pass
    else:
        errors.append(f"duplicate old/new owner: {logical}")
    return tuple(errors)


def validate_current_layout(root: Path = REPOSITORY_ROOT) -> tuple[str, ...]:
    errors = []
    seen_inodes = {}
    expected = set()
    for logical in KERNEL_LOGICAL_PATHS:
        errors.extend(_member_errors(root, logical))
        selected = current_path(root, logical)
        expected.add(selected.relative_to(root).as_posix())
        try:
            status = selected.lstat()
        except FileNotFoundError:
            continue
        if stat.S_ISREG(status.st_mode) and not stat.S_ISLNK(status.st_mode):
            identity = (status.st_dev, status.st_ino)
            if identity in seen_inodes:
                errors.append(
                    f"shared inode: {seen_inodes[identity]} and "
                    f"{selected.relative_to(root).as_posix()}"
                )
            else:
                seen_inodes[identity] = selected.relative_to(root).as_posix()

    observed = {
        path.relative_to(root).as_posix()
        for path in (root / "kernel").rglob("*")
        if path.is_file() and path.suffix in (".c", ".h")
    }
    for path in sorted(expected - observed):
        errors.append(f"missing inventoried member: {path}")
    for path in sorted(observed - expected):
        errors.append(f"unexpected kernel member: {path}")
    return tuple(errors)


