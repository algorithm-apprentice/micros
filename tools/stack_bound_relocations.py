"""Exact retained object bytes after the closed, nonrelaxing RV64 link."""

from functools import lru_cache
import re

from tools.stack_bound_machine import signed
from tools.stack_bound_objects import function_symbols, instructions, relocations, section_bytes
from tools.stack_bound_types import StackEvidenceError, require_path, require_uint64
from tools.user_elf_format import _program_file_bytes


def linked_bytes(image, address, size):
    try:
        return _program_file_bytes(image, address, size)
    except ValueError as error:
        raise StackEvidenceError(f"linked bytes lack their exact file-backed range: {error}") from error


@lru_cache(maxsize=8)
def linked_section_owners(content, allocated_outputs):
    lines = content.splitlines()
    if not lines or lines[0].split() != ["VMA", "LMA", "Size", "Align", "Out", "In", "Symbol"]:
        raise StackEvidenceError("linked bytes have an unsupported input-section map")
    owners = {}
    output = None
    output_column = lines[0].index("Out")
    for line in lines[1:]:
        heading = re.fullmatch(
            r"\s*([0-9a-f]+)\s+([0-9a-f]+)\s+([0-9a-f]+)\s+([0-9]+)\s+(\S+)\s*", line,
        )
        if heading is not None and heading.start(5) == output_column:
            output = heading[5] if heading[5] in allocated_outputs else None
        if output is None or ":(" not in line:
            continue
        match = re.fullmatch(
            r"\s*([0-9a-f]+)\s+([0-9a-f]+)\s+([0-9a-f]+)\s+([0-9]+)"
            r"\s+(.+):\(([^()]+)\)\s*", line,
        )
        if match is None:
            raise StackEvidenceError("linked bytes have a malformed object-section owner")
        address, load_address, size = (int(match[index], 16) for index in (1, 2, 3))
        require_uint64(address, "linked section address")
        require_uint64(size, "linked section size")
        if match[5] == "<internal>":
            if match[6] not in (".rodata.str1.1", ".rodata.cst8"):
                raise StackEvidenceError("unsupported allocated linker-generated byte pool")
        elif not match[5].endswith((".o", ".obj")):
            raise StackEvidenceError("linked bytes have an unsupported source object")
        else:
            require_path(match[5])
        key = match[5], match[6]
        if address != load_address or not int(match[4]) or key in owners:
            raise StackEvidenceError("linked bytes have ambiguous input-section geometry")
        owners[key] = address, size
    if not owners:
        raise StackEvidenceError("linked bytes lack object-section ownership")
    return owners


@lru_cache(maxsize=8)
def defined_globals(symbols):
    result = {}
    for symbol in symbols:
        if symbol.binding == 1 and symbol.section_index:
            result.setdefault(symbol.name, []).append(symbol)
    return {name: tuple(entries) for name, entries in result.items()}


@lru_cache(maxsize=256)
def alignment_deletions(obj, section_index, address):
    section = obj.sections[section_index]
    data = section_bytes(obj, section) if section.section_type == 1 else b""
    deleted, removed, ending = [], 0, 0
    for point, kind, target, padding in sorted(relocations(obj, section_index), key=lambda row: row[0]):
        if kind != 43:
            continue
        alignment = 1 << padding.bit_length()
        if (
            section.flags & 4 == 0 or padding <= 0 or point < ending
            or point + padding > section.size or target.name or target.value
            or target.section_index != 0
        ):
            raise StackEvidenceError("ALIGN relocation has an unowned executable padding range")
        code = tuple(instructions(data[point:point + padding], point))
        if any((width, word) not in ((2, 1), (4, 0x13)) for _, width, word in code):
            raise StackEvidenceError("ALIGN relocation attempts to remove an actual instruction")
        retained = (-address - point + removed) % alignment
        if retained > padding or retained % 2:
            raise StackEvidenceError("ALIGN padding cannot establish the declared linked alignment")
        ending = point + padding
        if retained != padding:
            deleted.append((point + retained, ending))
            removed += padding - retained
    return tuple(deleted)


def linked_offset(obj, section_index, offset, address):
    section = obj.sections[section_index]
    if not 0 <= offset <= section.size:
        raise StackEvidenceError("linked offset leaves its source object section")
    removed = 0
    for start, end in alignment_deletions(obj, section_index, address):
        if start < offset < end:
            raise StackEvidenceError("linked relocation/function points inside deleted padding")
        if end <= offset:
            removed += end - start
    return offset - removed


def pooled_address(obj, section, target, addend, image, owners, hint):
    if (
        target.binding != 0 or section.flags not in (0x12, 0x32)
        or section.section_type != 1 or relocations(obj, section.index)
        or (section.name, section.entry_size) not in (
            (".rodata.str1.1", 1), (".rodata.cst8", 8),
        )
        or hint is None
    ):
        raise StackEvidenceError("relocation has no finite readonly merge-pool binding")
    data = section_bytes(obj, section)
    point = target.value + addend
    if not 0 <= point < len(data):
        raise StackEvidenceError("merged source operand escapes its object bytes")
    if section.flags & 0x20:
        start = data.rfind(b"\0", 0, point) + 1
        end = data.find(b"\0", point) + 1
        if not end:
            raise StackEvidenceError("merged source string lacks its complete terminator")
    else:
        start = point // 8 * 8
        end = start + 8
        if end > len(data):
            raise StackEvidenceError("merged scalar has an incomplete fixed-width entry")
    base = hint - (point - start)
    pool = owners.get(("<internal>", section.name))
    if pool is None or not pool[0] <= base or base + end - start > pool[0] + pool[1]:
        raise StackEvidenceError("linked merge operand leaves its exact linker-generated pool")
    programs = tuple(
        item for item in image.programs if item.program_type == 1
        and item.virtual_address <= base
        and base + end - start <= item.virtual_address + item.file_size
    )
    if len(programs) != 1 or programs[0].flags != 4 or (
        linked_bytes(image, base, end - start) != data[start:end]
    ):
        raise StackEvidenceError("linked readonly merge operand differs from its complete source entry")
    return hint


def symbol_address(obj, object_name, target, addend, owners, globals_by_name, image, hint=None):
    if target.section_index == 0xfff1:
        value = target.value
    elif target.section_index == 0:
        candidates = globals_by_name.get(target.name, ())
        if target.binding != 1 or len(candidates) != 1:
            raise StackEvidenceError("relocation has no exact linked global symbol")
        value = candidates[0].value
    elif 0 < target.section_index < len(obj.sections):
        section = obj.sections[target.section_index]
        owner = owners.get((object_name, section.name))
        if owner is None and section.flags & 0x10:
            return pooled_address(obj, section, target, addend, image, owners, hint)
        if owner is None or target.value > section.size:
            raise StackEvidenceError("relocation borrows an unretained object section")
        value = owner[0] + linked_offset(obj, section.index, target.value + addend, owner[0])
        addend = 0
    else:
        raise StackEvidenceError("relocation has an unsupported symbol owner")
    value += addend
    require_uint64(value, "relocated symbol address")
    return value


def branch_word(word, kind, displacement):
    widths = {16: 13, 17: 21, 44: 9, 45: 12}
    bits = widths[kind]
    if displacement % 2 or not -(1 << (bits - 1)) <= displacement < (1 << (bits - 1)):
        raise StackEvidenceError("linked branch displacement exceeds its actual encoding")
    if kind == 16 and word & 0x7f == 0x63:
        return (
            word & 0x01fff07f | (displacement >> 12 & 1) << 31
            | (displacement >> 5 & 63) << 25 | (displacement >> 1 & 15) << 8
            | (displacement >> 11 & 1) << 7
        )
    if kind == 17 and word & 0x7f == 0x6f:
        return (
            word & 0x00000fff | (displacement >> 20 & 1) << 31
            | (displacement >> 1 & 1023) << 21 | (displacement >> 11 & 1) << 20
            | (displacement >> 12 & 255) << 12
        )
    if kind == 44 and word & 3 == 1 and word >> 13 in (6, 7):
        return (
            word & 0xe383 | (displacement >> 8 & 1) << 12
            | (displacement >> 3 & 3) << 10 | (displacement >> 6 & 3) << 5
            | (displacement >> 1 & 3) << 3 | (displacement >> 5 & 1) << 2
        )
    if kind == 45 and word & 0xe003 == 0xa001:
        return (
            word & 0xe003 | (displacement >> 11 & 1) << 12
            | (displacement >> 4 & 1) << 11 | (displacement >> 8 & 3) << 9
            | (displacement >> 10 & 1) << 8 | (displacement >> 6 & 1) << 7
            | (displacement >> 7 & 1) << 6 | (displacement >> 1 & 7) << 3
            | (displacement >> 5 & 1) << 2
        )
    raise StackEvidenceError("branch relocation does not own its exact instruction")


def high_low(displacement):
    high = (displacement + 0x800) & ~0xfff
    if not -(1 << 31) <= high < (1 << 31):
        raise StackEvidenceError("PC-relative relocation exceeds the admitted medany range")
    return high & 0xfffff000, displacement - high


def relocate_section(obj, section, object_name, address, owners, globals_by_name, image):
    expected = bytearray(section_bytes(obj, section))
    references = {}
    for point, kind, target, addend in relocations(obj, section.index):
        if kind in (43, 51):
            if not 0 <= point < section.size:
                raise StackEvidenceError("ALIGN/RELAX marker escapes its input section")
            continue
        if point in references:
            raise StackEvidenceError("overlapping linked instruction/data relocation")
        references[point] = kind, target, addend
    written = set()

    def put(point, size, word):
        if point < 0 or point + size > len(expected) or written & set(range(point, point + size)):
            raise StackEvidenceError("linked relocation overlaps or leaves its owned bytes")
        expected[point:point + size] = word.to_bytes(size, "little")
        written.update(range(point, point + size))

    def word_at(point, size):
        if point < 0 or point + size > len(expected):
            raise StackEvidenceError("linked relocation has truncated instruction/data bytes")
        return int.from_bytes(expected[point:point + size], "little")

    def destination(point, kind, target, addend):
        hint = None
        if kind == 2:
            hint = int.from_bytes(linked_bytes(
                image, address + linked_offset(obj, section.index, point, address), 8,
            ), "little")
        elif kind == 23:
            lowers = tuple(
                offset for offset, (lower_kind, lower_target, extra) in references.items()
                if lower_kind in (24, 25) and lower_target.section_index == section.index
                and lower_target.value + extra == point
            )
            if not lowers:
                raise StackEvidenceError("PC-relative upper has no complete owned lower pair")
            placed = address + linked_offset(obj, section.index, point, address)
            upper = int.from_bytes(linked_bytes(image, placed, 4), "little")
            hints = set()
            for offset in lowers:
                lower = int.from_bytes(linked_bytes(
                    image, address + linked_offset(obj, section.index, offset, address), 4,
                ), "little")
                low = lower >> 20 if references[offset][0] == 24 else (
                    lower >> 25 << 5 | lower >> 7 & 31
                )
                hints.add(placed + signed(upper & 0xfffff000, 32) + signed(low, 12))
            if len(hints) != 1:
                raise StackEvidenceError("shared PC-relative upper has inconsistent linked lower operands")
            hint, = hints
        return symbol_address(
            obj, object_name, target, addend, owners, globals_by_name, image, hint,
        )

    for point, (kind, target, addend) in references.items():
        word = word_at(point, 2 if kind in (44, 45) else 4)
        if kind in (24, 25):
            if target.section_index != section.index:
                raise StackEvidenceError("PC-relative lower pair borrows another object section")
            producer = target.value + addend
            upper = references.get(producer)
            if upper is None or upper[0] != 23:
                raise StackEvidenceError("PC-relative lower pair lacks its owned upper relocation")
            upper_word = int.from_bytes(section_bytes(obj, section)[producer:producer + 4], "little")
            valid = (
                kind == 24 and word & 0x7f in (3, 0x13, 0x1b, 0x67) and word >> 20 == 0
                or kind == 25 and word & 0x7f == 0x23 and word & 0xfe000f80 == 0
            )
            if not valid or word >> 15 & 31 != upper_word >> 7 & 31:
                raise StackEvidenceError("PC-relative lower instruction borrows another base register")
            value = destination(producer, 23, upper[1], upper[2])
            _, low = high_low(value - address - linked_offset(obj, section.index, producer, address))
            encoded = (
                word & 0x000fffff | (low & 0xfff) << 20 if kind == 24 else
                word & 0x01fff07f | (low & 0xfe0) << 20 | (low & 31) << 7
            )
            put(point, 4, encoded)
            continue
        value = destination(point, kind, target, addend)
        if kind == 2:
            if word_at(point, 8) != 0:
                raise StackEvidenceError("absolute pointer relocation has nonzero borrowed source bytes")
            put(point, 8, value)
        elif kind in (16, 17, 44, 45):
            put(point, 2 if kind in (44, 45) else 4, branch_word(
                word, kind, value - address - linked_offset(obj, section.index, point, address),
            ))
        elif kind == 23:
            if word & 0x7f != 0x17 or word >> 12 or word >> 7 & 31 == 0:
                raise StackEvidenceError("PC-relative upper relocation has no exact AUIPC")
            high, _ = high_low(value - address - linked_offset(obj, section.index, point, address))
            put(point, 4, word & 0xfff | high)
        elif kind in (18, 19):
            lower = word_at(point + 4, 4)
            if (
                word & 0x7f != 0x17 or word >> 12 or word >> 7 & 31 == 0
                or lower & 0x707f != 0x67 or lower >> 20
                or word >> 7 & 31 != lower >> 15 & 31 or lower >> 7 & 31 not in (0, 1)
            ):
                raise StackEvidenceError("linked call relocation lost its exact register pair")
            high, low = high_low(value - address - linked_offset(obj, section.index, point, address))
            put(point, 4, word & 0xfff | high)
            put(point + 4, 4, lower & 0x000fffff | (low & 0xfff) << 20)
        else:
            raise StackEvidenceError(f"unsupported allocated RV64 relocation: {kind}")
    deleted = alignment_deletions(obj, section.index, address)
    cursor, pieces = 0, []
    for start, end in deleted:
        if written & set(range(start, end)):
            raise StackEvidenceError("ALIGN padding overlaps an actual instruction/data relocation")
        pieces.append(expected[cursor:start])
        cursor = end
    pieces.append(expected[cursor:])
    return b"".join(pieces)


def require_section_geometry(image, section, address, size):
    end = address + size
    require_uint64(end, "linked section end")
    containing = tuple(
        item for item in image.sections if item.flags & 2
        and item.address <= address and end <= item.address + item.size
    )
    programs = tuple(
        item for item in image.programs if item.program_type == 1
        and item.virtual_address <= address and end <= item.virtual_address + item.memory_size
    )
    flags = 4 | (1 if section.flags & 4 else 0) | (2 if section.flags & 1 else 0)
    if (
        len(containing) != 1 or len(programs) != 1
        or containing[0].flags & 7 != section.flags & 7
        or containing[0].section_type != section.section_type
        or programs[0].flags != flags or address % section.alignment
        or section.section_type == 1 and end > programs[0].virtual_address + programs[0].file_size
    ):
        raise StackEvidenceError("linked object section lost its exact range/type/permissions")


def verify_linked_object(obj, object_name, image, map_text):
    require_path(object_name)
    owners = linked_section_owners(map_text, frozenset(
        section.name for section in image.sections if section.flags & 2
    ))
    globals_by_name = defined_globals(image.symbols)
    retained = {}
    for section in obj.sections:
        owner = owners.get((object_name, section.name))
        if owner is None or not section.flags & 2 or not section.size:
            continue
        address, size = owner
        if size != linked_offset(obj, section.index, section.size, address) or not section.alignment:
            raise StackEvidenceError("linked input-section size differs from its actual object")
        require_section_geometry(image, section, address, size)
        if section.section_type == 1:
            expected = relocate_section(obj, section, object_name, address, owners, globals_by_name, image)
            if linked_bytes(image, address, size) != expected:
                raise StackEvidenceError("linked bytes differ from the complete relocated object")
        elif section.section_type != 8 or relocations(obj, section.index):
            raise StackEvidenceError("unsupported allocated object section or BSS relocation")
        retained[section.index] = address
    for symbol in function_symbols(obj).values():
        if symbol.binding == 1 and globals_by_name.get(symbol.name) and (
            symbol.section_index not in retained
            or not any((item.value, item.size) == (
                retained[symbol.section_index] + linked_offset(
                    obj, symbol.section_index, symbol.value, retained[symbol.section_index],
                ),
                linked_offset(
                    obj, symbol.section_index, symbol.value + symbol.size, retained[symbol.section_index],
                ) - linked_offset(obj, symbol.section_index, symbol.value, retained[symbol.section_index]),
            ) for item in globals_by_name[symbol.name])
        ):
            raise StackEvidenceError("retained global function lacks its exact object/map bytes")
    if not retained:
        raise StackEvidenceError("object has no retained linked byte inventory")
    return retained
