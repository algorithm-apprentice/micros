MICROS_TRAP_ASSERT_OFFSET(s9, MICROS_TRAP_CONTEXT_S9_OFFSET);
MICROS_TRAP_ASSERT_OFFSET(s10, MICROS_TRAP_CONTEXT_S10_OFFSET);
MICROS_TRAP_ASSERT_OFFSET(s11, MICROS_TRAP_CONTEXT_S11_OFFSET);
MICROS_TRAP_ASSERT_OFFSET(t3, MICROS_TRAP_CONTEXT_T3_OFFSET);
MICROS_TRAP_ASSERT_OFFSET(t4, MICROS_TRAP_CONTEXT_T4_OFFSET);
MICROS_TRAP_ASSERT_OFFSET(t5, MICROS_TRAP_CONTEXT_T5_OFFSET);
MICROS_TRAP_ASSERT_OFFSET(t6, MICROS_TRAP_CONTEXT_T6_OFFSET);
