#define MICROS_TRAP_ASSERT_OFFSET(field, offset) \
    _Static_assert( \
        offsetof(struct micros_trap_frame, field) == (offset), \
        "trap " #field " offset mismatch" \
    )

MICROS_TRAP_ASSERT_OFFSET(ra, MICROS_TRAP_CONTEXT_RA_OFFSET);
MICROS_TRAP_ASSERT_OFFSET(sp, MICROS_TRAP_CONTEXT_SP_OFFSET);
MICROS_TRAP_ASSERT_OFFSET(gp, MICROS_TRAP_CONTEXT_GP_OFFSET);
MICROS_TRAP_ASSERT_OFFSET(tp, MICROS_TRAP_CONTEXT_TP_OFFSET);
MICROS_TRAP_ASSERT_OFFSET(t0, MICROS_TRAP_CONTEXT_T0_OFFSET);
MICROS_TRAP_ASSERT_OFFSET(t1, MICROS_TRAP_CONTEXT_T1_OFFSET);
MICROS_TRAP_ASSERT_OFFSET(t2, MICROS_TRAP_CONTEXT_T2_OFFSET);
MICROS_TRAP_ASSERT_OFFSET(s0, MICROS_TRAP_CONTEXT_S0_OFFSET);
MICROS_TRAP_ASSERT_OFFSET(s1, MICROS_TRAP_CONTEXT_S1_OFFSET);
MICROS_TRAP_ASSERT_OFFSET(a0, MICROS_TRAP_CONTEXT_A0_OFFSET);
MICROS_TRAP_ASSERT_OFFSET(a1, MICROS_TRAP_CONTEXT_A1_OFFSET);
